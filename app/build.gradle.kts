import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("com.google.devtools.ksp")
}

android {
    namespace = "com.backlogzero.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.backlogzero.app"
        minSdk = 26
        targetSdk = 34
        versionCode = (findProperty("versionCode") as String?)?.toInt() ?: 1
        versionName = (findProperty("versionName") as String?) ?: "1.0"

        // Gratis API-sleutels voor online zoeken (TMDB: films/series, RAWG: games). Uit ~/.gradle/gradle.properties
        // of een omgevingsvariabele (CI-secret). Leeg = zoeken voor dat type staat uit; boeken werken altijd.
        for (name in listOf("TMDB_API_KEY", "RAWG_API_KEY")) {
            val key = (findProperty(name) as String?) ?: System.getenv(name) ?: ""
            buildConfigField("String", name, "\"${key.trim()}\"")
        }
    }

    // Eigen ondertekeningssleutel staat in keystore.properties (niet in git).
    // Zonder dat bestand valt release terug op de debug-sleutel, zodat CI en nieuwe checkouts gewoon bouwen.
    val ksProps = Properties().apply {
        val f = rootProject.file("keystore.properties")
        if (f.exists()) f.inputStream().use { load(it) }
    }
    signingConfigs {
        create("release") {
            if (ksProps.isNotEmpty()) {
                storeFile = rootProject.file(ksProps.getProperty("storeFile"))
                storePassword = ksProps.getProperty("storePassword")
                keyAlias = ksProps.getProperty("keyAlias")
                keyPassword = ksProps.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (ksProps.isNotEmpty()) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    composeOptions { kotlinCompilerExtensionVersion = "1.5.14" }
    packaging { resources.excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    lint { abortOnError = false }
}

